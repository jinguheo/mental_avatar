function cell(text: string) {
  const cls = STATUS[text]
  return cls ? <span className={'whitespace-nowrap rounded px-2 py-0.5 text-xs font-medium ' + cls}>{text}</span> : text
}

function toMarkdown(): string {
  const out: string[] = ['# ' + TITLE, '', '> 작성 기준일 2026-10-19. 측정하지 않은 것은 결과로 쓰지 않았다. 일치(sync)는 아직 측정 전이다.', '']
  for (const section of SECTIONS) {
    out.push('## ' + section.title, '')
    for (const block of section.blocks) {
      if (block.t === 'p') out.push(block.text, '')
      else if (block.t === 'ul') out.push(...block.items.map(item => '- ' + item), '')
      else {
        const esc = (value: string) => value.replace(/\|/g, '\\|')
        out.push('| ' + block.head.map(esc).join(' | ') + ' |', '| ' + block.head.map(() => '---').join(' | ') + ' |')
        out.push(...block.rows.map(row => '| ' + row.map(esc).join(' | ') + ' |'), '')
        if (block.note) out.push('> ' + block.note, '')
      }
    }
  }
  return out.join('\n')
}

